func TestIsControlFrame(t *testing.T) {
	eapol := []byte{
		0x01, 0x80, 0xc2, 0x00, 0x00, 0x03,
		0xaa, 0xbb, 0xcc, 0xdd, 0xee, 0xff,
		0x88, 0x8e,
		0x01, 0x00,
	}
	if !isControlFrame(eapol) {
		t.Fatalf("expected EAPOL control frame")
	}

	vlanLLDP := []byte{
		0x01, 0x80, 0xc2, 0x00, 0x00, 0x0e,
		0xaa, 0xbb, 0xcc, 0xdd, 0xee, 0xff,
		0x81, 0x00, 0x00, 0x64,
		0x88, 0xcc,
	}
	if !isControlFrame(vlanLLDP) {
		t.Fatalf("expected VLAN LLDP control frame")
	}

	stackedVLANEAPOL := []byte{
		0x01, 0x80, 0xc2, 0x00, 0x00, 0x03,
		0xaa, 0xbb, 0xcc, 0xdd, 0xee, 0xff,
		0x88, 0xa8, 0x00, 0x64,
		0x81, 0x00, 0x00, 0xc8,
		0x88, 0x8e,
	}
	if !isControlFrame(stackedVLANEAPOL) {
		t.Fatalf("expected stacked VLAN EAPOL control frame")
	}

	ip := []byte{
		0xff, 0xff, 0xff, 0xff, 0xff, 0xff,
		0xaa, 0xbb, 0xcc, 0xdd, 0xee, 0xff,
		0x08, 0x00,
	}
	if isControlFrame(ip) {
		t.Fatalf("did not expect IPv4 broadcast to be relayed")
	}
}

